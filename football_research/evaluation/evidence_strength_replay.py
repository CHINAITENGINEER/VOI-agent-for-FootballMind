"""Paired evaluator for coherent strength adaptation and unchanged references.

Full rows and outcomes stay in this supervisor. The selected trajectories
are generated by the public-state-only strict VoI policy before scoring.
"""
from __future__ import annotations

from collections import Counter, defaultdict
import json
from pathlib import Path

import numpy as np

from ..acquisition.experiment import losses, outcome
from ..acquisition.experiment_round8 import run_episode as run_reference
from ..acquisition.joint_voi import LearnedJointVOIPolicy
from ..acquisition.state import parse_time
from .learned_voi_replay import run_learned_voi_episode, score_reconstructed_trajectory

STRATEGIES = ("base-only", "original-strict-voi", "adapted-strict-voi",
              "original-all-available", "adapted-all-available")


def evaluate_fold(rows, reference, adapted, actions, *, lambda_money, output, fold,
                  limits=None, evidence_grade="reused_historical_exploratory"):
    limits = limits or {"money": .05, "requests": 2}
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    policies = {"original-strict-voi": LearnedJointVOIPolicy(reference, lambda_cost={"money": lambda_money}),
                "adapted-strict-voi": LearnedJointVOIPolicy(adapted, lambda_cost={"money": lambda_money})}
    results, updates = [], []
    with (output/"trajectories.jsonl").open("w", encoding="utf-8") as trace_file, \
            (output/"evaluation-sidecars.jsonl").open("w", encoding="utf-8") as eval_file:
        for row in sorted(rows, key=lambda r: (parse_time(r["kickoff"]), r["match_id"])):
            initial = None
            # Finish both actors before passing this match's outcome to scoring.
            trajectories = {strategy: run_learned_voi_episode(row, policy, actions, limits=limits)
                            for strategy, policy in policies.items()}
            for strategy, trajectory in trajectories.items():
                if initial is not None and initial != trajectory["initial_probabilities"]:
                    raise ValueError("Paired policies do not share the same initial forecast")
                initial = trajectory["initial_probabilities"]
                evaluation = score_reconstructed_trajectory(trajectory, row)
                envelope = {"fold": fold, "strategy": strategy, "evidence_grade": evidence_grade}
                trace_file.write(json.dumps({**envelope, "trajectory": trajectory}, allow_nan=False)+"\n")
                eval_file.write(json.dumps({**envelope, "evaluation": evaluation}, allow_nan=False)+"\n")
                results.append({**envelope, "match_id": row["match_id"], "kickoff": row["kickoff"],
                                "prediction_cutoff": row["prediction_cutoff"],
                                "model_version": trajectory["model_version"],
                                "initial_probabilities": initial,
                                "final_probabilities": trajectory["final_probabilities"],
                                "actions": trajectory["actions"], "cost": trajectory["cost"],
                                "stop_reason": trajectory["terminal_selection"]["reason"],
                                **evaluation["after_loss"]})
                for cycle in trajectory["cycles"]:
                    if cycle["update"] is None:
                        continue
                    aid = cycle["update"]["action_id"]
                    value = next(c["value"] for c in cycle["decision"]["candidates"] if c["action_id"] == aid)
                    actual = next(s for s in evaluation["steps"] if s["decision_digest"] == cycle["update"]["decision_digest"])
                    updates.append({**envelope, "match_id": row["match_id"], "action_id": aid,
                                    "acquired_before": trajectory["actions"][:cycle["step"]],
                                    "model_evsi": value["gross_evsi"], "net_voi": value["net_voi"],
                                    "actual_log_loss_reduction": actual["realized_log_loss_reduction"]})
            baseline = {"fold": fold, "strategy": "base-only", "match_id": row["match_id"],
                        "kickoff": row["kickoff"], "prediction_cutoff": row["prediction_cutoff"],
                        "model_version": reference.model_version, "initial_probabilities": initial,
                        "final_probabilities": initial, "actions": [],
                        "cost": {"money": 0., "requests": 0., "latency_ms": 0., "tokens": 0.},
                        "stop_reason": "base_only_reference", **losses(initial, outcome(row))}
            results.append(baseline)
            for label, model in (("original", reference), ("adapted", adapted)):
                record, _ = run_reference(row, model, actions, strategy="all-available",
                                           budget_money=limits["money"], lambda_money=lambda_money,
                                           seed=0, design={"request_budget": limits["requests"]})
                if record["initial_probabilities"] != initial:
                    raise ValueError("All-available reference changed initial forecast")
                record.update(strategy=label+"-all-available", fold=fold)
                results.append(record)
    return results, updates


def summarize_paired(results, updates):
    indexed = {strategy: {} for strategy in STRATEGIES}
    for row in results:
        group = indexed[row["strategy"]]
        if row["match_id"] in group:
            raise ValueError("Repeated match in paired strategy results")
        group[row["match_id"]] = row
    identity = set(indexed[STRATEGIES[0]])
    if not identity or any(set(v) != identity for v in indexed.values()):
        raise ValueError("Paired strategies require the same nonempty match identities")
    metrics = {}
    for strategy, rows in indexed.items():
        values = list(rows.values())
        metrics[strategy] = {"unique_matches": len(values),
            "mean_log_loss": float(np.mean([r["log_loss"] for r in values])),
            "mean_brier_score": float(np.mean([r["brier_score"] for r in values])),
            "mean_queries": float(np.mean([r["cost"]["requests"] for r in values])),
            "mean_cost": float(np.mean([r["cost"]["money"] for r in values])),
            "mean_utility_loss": float(np.mean([r["log_loss"]+.5*r["cost"]["money"] for r in values])),
            "paths": dict(Counter(" -> ".join(r["actions"]) or "no_query" for r in values)),
            "terminal_reasons": dict(Counter(r["stop_reason"] for r in values))}
    comparisons = []
    for reference in (s for s in STRATEGIES if s != "adapted-strict-voi"):
        a, b = indexed["adapted-strict-voi"], indexed[reference]
        blocks = defaultdict(list)
        for mid in sorted(identity):
            if a[mid]["kickoff"] != b[mid]["kickoff"]:
                raise ValueError("Paired match kickoff mismatch")
            delta = a[mid]["log_loss"]-b[mid]["log_loss"]
            utility = delta+.5*(a[mid]["cost"]["money"]-b[mid]["cost"]["money"])
            week = parse_time(a[mid]["kickoff"]).isocalendar()[:2]
            blocks[week].append([delta, utility])
        arrays = [np.asarray(blocks[k]) for k in sorted(blocks)]
        sums, counts = np.asarray([v.sum(axis=0) for v in arrays]), np.asarray([len(v) for v in arrays])
        draws = np.random.default_rng(1729).integers(0, len(arrays), size=(2000, len(arrays)))
        boot = sums[draws].sum(axis=1)/counts[draws].sum(axis=1)[:, None]
        difference = sums.sum(axis=0)/counts.sum()
        comparisons.append({"strategy": "adapted-strict-voi", "reference": reference,
                            "unique_matches": len(identity), "utc_week_blocks": len(arrays),
                            "mean_log_loss_difference": float(difference[0]),
                            "log_loss_interval_95_descriptive": np.quantile(boot[:, 0], [.025, .975]).tolist(),
                            "mean_utility_loss_difference": float(difference[1]),
                            "utility_interval_95_descriptive": np.quantile(boot[:, 1], [.025, .975]).tolist(),
                            "interval_scope": "paired UTC-week bootstrap; no research-selection, model-fit or multiplicity correction"})
    gain_summaries = []
    for strategy in ("original-strict-voi", "adapted-strict-voi"):
        for aid in ("results_view", "xg_view"):
            subset = [u for u in updates if u["strategy"] == strategy and u["action_id"] == aid]
            gain_summaries.append({"strategy": strategy, "action_id": aid, "selected_queries": len(subset),
                                  "mean_model_evsi": float(np.mean([u["model_evsi"] for u in subset])) if subset else None,
                                  "mean_actual_gain": float(np.mean([u["actual_log_loss_reduction"] for u in subset])) if subset else None,
                                  "scope": "selected-query descriptive gain; not an unbiased calibration estimate"})
    return {"metrics": metrics, "paired_comparisons": comparisons, "selected_gain_diagnostics": gain_summaries}
